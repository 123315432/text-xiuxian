export function t(key: string, ...args: (string | number)[]): string {
  const entry = translations[key]
  if (!entry) return key
  let text = entry[currentLocale] ?? entry.zh ?? key
  // Simple placeholder replacement: {0}, {1}, etc.
  for (let i = 0; i < args.length; i++) {
    text = text.replaceAll(`{${i}}`, String(args[i]))
  }
  return text
}

// For data objects that have name/nameEn, desc/descEn fields
export function tName(obj: { name: string; nameEn?: string }): string {
  return currentLocale === 'en' && obj.nameEn ? obj.nameEn : obj.name
}

export function tDesc(obj: { desc?: string; descEn?: string; text?: string; textEn?: string }): string {
  if (currentLocale === 'en') {
    return obj.descEn ?? obj.textEn ?? obj.desc ?? obj.text ?? ''
  }
  return obj.desc ?? obj.text ?? ''
}
